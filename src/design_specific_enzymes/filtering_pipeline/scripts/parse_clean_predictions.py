#!/usr/bin/env python3
"""Parse CLEAN prediction output into a standardized metric CSV.

Each CLEAN line is ``<sample_id><sep>EC:x.x.x.x/dist,EC:...`` where ``<sep>`` is
whitespace or a comma. ``sample_id`` is mapped back to a FASTA record by, in
order: exact header, first header token, header up to ``|``, and finally a
trailing integer used as the record index (e.g. ``file_3`` -> record 3). The
header match comes first so headers such as ``12_ppl_3.4`` (generated by
``dpo_optimize_and_generate.py``) are not misread as an index.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import pandas as pd

PRED_PATTERN = re.compile(r"EC:([^/,\s]+)")
LINE_SPLIT = re.compile(r"[\s,]+")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Parse CLEAN prediction output.")
    parser.add_argument("--clean_output", required=True, help="CLEAN output file.")
    parser.add_argument("--input_fasta", required=True, help="Original FASTA used for CLEAN.")
    parser.add_argument("--output_csv", required=True)
    parser.add_argument("--target_ec", default="")
    return parser.parse_args()


def read_fasta(path: Path) -> list[tuple[str, str]]:
    """Return (header, sequence) records in file order."""
    records: list[tuple[str, str]] = []
    header = None
    current: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(">"):
            if header is not None:
                records.append((header, "".join(current)))
            header = line[1:].strip()
            current = []
        else:
            current.append(line.strip())
    if header is not None:
        records.append((header, "".join(current)))
    return records


def md5(sequence: str) -> str:
    return hashlib.md5(sequence.encode("utf-8")).hexdigest()


def build_header_index(records: list[tuple[str, str]]) -> dict[str, int]:
    """Map header spellings CLEAN might report to record indices.

    Ambiguous spellings (shared by several records) are dropped so they fall
    through to the index fallback instead of silently picking one record.
    """
    index: dict[str, int] = {}
    ambiguous: set[str] = set()
    for i, (header, _) in enumerate(records):
        for key in (header, header.split()[0] if header.split() else header, header.split("|")[0]):
            if key in index and index[key] != i:
                ambiguous.add(key)
            index.setdefault(key, i)
    for key in ambiguous:
        index.pop(key, None)
    return index


def sample_to_index(sample_id: str) -> int | None:
    sample_id = sample_id.strip()
    candidate = sample_id.split("_")[-1] if "_" in sample_id else sample_id
    try:
        return int(candidate)
    except ValueError:
        return None


def resolve_record(sample_id: str, header_index: dict[str, int], n_records: int) -> int | None:
    if sample_id in header_index:
        return header_index[sample_id]
    seq_index = sample_to_index(sample_id)
    if seq_index is not None and 0 <= seq_index < n_records:
        return seq_index
    return None


def first_predicted_ec(text: str) -> str:
    match = PRED_PATTERN.search(text or "")
    return match.group(1) if match else ""


def main() -> None:
    args = parse_args()
    records = read_fasta(Path(args.input_fasta))
    header_index = build_header_index(records)

    rows = []
    unresolved = 0
    with open(args.clean_output, encoding="utf-8", errors="replace") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            fields = LINE_SPLIT.split(line, maxsplit=1)
            sample_id = fields[0]
            pred_text = fields[1] if len(fields) > 1 else ""
            seq_index = resolve_record(sample_id, header_index, len(records))
            if seq_index is None:
                unresolved += 1
                continue
            sequence = records[seq_index][1]
            rows.append(
                {
                    "sample_id": sample_id,
                    "sequence_index": seq_index,
                    "sequence_md5": md5(sequence),
                    "predicted_ec": first_predicted_ec(pred_text),
                    "target_ec": args.target_ec,
                }
            )

    if unresolved:
        print(
            f"WARNING: {unresolved} CLEAN line(s) could not be matched to a FASTA record.",
            file=sys.stderr,
        )
    if not rows:
        sys.exit(
            f"ERROR: no CLEAN predictions in {args.clean_output} could be matched to "
            f"{args.input_fasta} ({len(records)} FASTA records). Check that CLEAN was run "
            "on this FASTA and that its sample ids match the FASTA headers."
        )

    out = pd.DataFrame(rows)
    Path(args.output_csv).parent.mkdir(parents=True, exist_ok=True)
    out.to_csv(args.output_csv, index=False)
    print(f"Wrote {len(out)} parsed CLEAN rows -> {args.output_csv}")


if __name__ == "__main__":
    main()
